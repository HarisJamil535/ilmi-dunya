const mongoose = require("mongoose");
const Assessment = require("../models/Assessment");
const Chapter = require("../models/Chapter");
const Question = require("../models/Question");
const Topic = require("../models/Topic");
const { fail } = require("./publishing");
const { timingOf, timingFields, parseTiming, sameTiming } = require("./testTiming");

// Tests a teacher built (not the ones assembled for students on the fly).
const teacherTests = { isAutoGenerated: { $ne: true }, createdBy: { $exists: true }, status: { $ne: "archived" } };
const liveMcq = { contentType: { $nin: ["long_question", "short_question"] }, type: { $in: ["standard_mcq", "scenario_mcq"] }, status: { $ne: "archived" } };
const MAX_TEST_QUESTIONS = 500;

// A published test is open now unless it is scheduled for later or has already closed.
const openNow = (now = new Date()) => ({
    status: "published",
    $and: [
        { $or: [{ startsAt: null }, { startsAt: { $exists: false } }, { startsAt: { $lte: now } }] },
        { $or: [{ endsAt: null }, { endsAt: { $exists: false } }, { endsAt: { $gt: now } }] },
    ],
});

function testState(test, now) {
    if (test.status !== "published") return "off";
    if (test.endsAt && new Date(test.endsAt) <= now) return "closed";
    if (test.startsAt && new Date(test.startsAt) > now) return "scheduled";
    return "live";
}

// Summarises a set of tests into one switch state for the teacher.
function summarise(tests, mcqCount, now) {
    const states = tests.filter(test => test.questionCount > 0).map(test => ({ state: testState(test, now), startsAt: test.startsAt }));
    const scheduled = states.filter(item => item.state === "scheduled").map(item => new Date(item.startsAt)).sort((a, b) => a - b);
    let state = "empty";
    if (states.some(item => item.state === "live")) state = "live";
    else if (scheduled.length) state = "scheduled";
    else if (states.length || mcqCount) state = "off";
    return { state, opensAt: state === "scheduled" ? scheduled[0] : null };
}

const subjectFilter = query => {
    const filter = {};
    for (const key of ["board", "class", "group", "subject"]) {
        if (!query[key]) continue;
        if (!mongoose.isValidObjectId(query[key])) fail(`Choose a valid ${key}.`);
        filter[key] = new mongoose.Types.ObjectId(String(query[key]));
    }
    if (!filter.subject) fail("Choose a subject.");
    return filter;
};

// Every chapter and topic of a subject with its test publishing state.
async function publishingOverview(query, now = new Date()) {
    const filter = subjectFilter(query);
    const chapters = await Chapter.find(filter).select("name chapterNumber testTiming").sort({ chapterNumber: 1, name: 1 }).lean();
    const chapterIds = chapters.map(chapter => chapter._id);
    const [topics, tests, mcqs] = await Promise.all([
        Topic.find({ chapterId: { $in: chapterIds } }).select("name topicNumber chapterId").lean(),
        Assessment.find({ ...teacherTests, chapter: { $in: chapterIds }, type: { $in: ["topic_test", "chapter_test"] } })
            .select("title type chapter topic status startsAt endsAt timingMode secondsPerQuestion durationMinutes questions.question").lean(),
        Question.find({ ...liveMcq, chapter: { $in: chapterIds } }).select("_id chapter topic").lean(),
    ]);

    const inTests = new Set(tests.flatMap(test => (test.questions || []).map(item => String(item.question))));
    const byTopic = new Map();
    const bucket = key => {
        if (!byTopic.has(key)) byTopic.set(key, { tests: [], mcqs: 0, newMcqs: 0 });
        return byTopic.get(key);
    };
    for (const test of tests) {
        const entry = { _id: test._id, title: test.title, type: test.type, status: test.status, startsAt: test.startsAt || null, endsAt: test.endsAt || null, questionCount: test.questions?.length || 0, timing: timingOf(test) };
        entry.state = testState(entry, now);
        bucket(test.type === "topic_test" && test.topic ? String(test.topic) : `chapter:${test.chapter}`).tests.push(entry);
    }
    for (const question of mcqs) {
        const entry = bucket(question.topic ? String(question.topic) : `chapter:${question.chapter}`);
        entry.mcqs += 1;
        if (!inTests.has(String(question._id))) entry.newMcqs += 1;
    }

    const sortTopics = (left, right) => String(left.topicNumber || "").localeCompare(String(right.topicNumber || ""), undefined, { numeric: true, sensitivity: "base" });
    return chapters.map(chapter => {
        const chapterTopics = topics.filter(topic => String(topic.chapterId) === String(chapter._id)).sort(sortTopics).map(topic => {
            const entry = byTopic.get(String(topic._id)) || { tests: [], mcqs: 0, newMcqs: 0 };
            return { _id: topic._id, name: topic.name, topicNumber: topic.topicNumber, mcqCount: entry.mcqs, newMcqCount: entry.newMcqs, tests: entry.tests, timing: sharedTiming(entry.tests), ...summarise(entry.tests, entry.mcqs, now) };
        });
        const own = byTopic.get(`chapter:${chapter._id}`) || { tests: [], mcqs: 0, newMcqs: 0 };
        const allTests = [...chapterTopics.flatMap(topic => topic.tests), ...own.tests];
        const mcqCount = chapterTopics.reduce((sum, topic) => sum + topic.mcqCount, own.mcqs);
        return {
            _id: chapter._id,
            name: chapter.name,
            chapterNumber: chapter.chapterNumber,
            mcqCount,
            unassignedMcqCount: own.mcqs,
            chapterTests: own.tests,
            topics: chapterTopics,
            // The chapter's own time, or null when the complete chapter test follows its topic tests.
            timing: chapter.testTiming?.mode ? { mode: chapter.testTiming.mode, ...(chapter.testTiming.mode === "per_question" ? { secondsPerQuestion: chapter.testTiming.secondsPerQuestion } : { minutes: chapter.testTiming.minutes }) } : null,
            ...summarise(allTests, mcqCount, now),
        };
    });
}

// One timing when every test of a topic shares it, "mixed" when they differ, null with no tests.
function sharedTiming(tests) {
    if (!tests.length) return null;
    return tests.every(test => sameTiming(test.timing, tests[0].timing)) ? tests[0].timing : { mode: "mixed" };
}

async function questionsFor(filter) {
    const docs = await Question.find({ ...liveMcq, ...filter }).select("_id marks estimatedTimeSeconds").sort({ createdAt: 1, _id: 1 }).limit(MAX_TEST_QUESTIONS).lean();
    return docs;
}

const asTestQuestions = (docs, start = 0) => docs.map((doc, index) => ({ question: doc._id, marks: Number(doc.marks) > 0 ? Number(doc.marks) : 1, order: start + index + 1, required: true }));

// Builds a ready topic test from every MCQ saved under the topic.
async function createTopicTest(chapter, topic, adminId) {
    const docs = await questionsFor({ topic: topic._id });
    if (!docs.length) return null;
    const questions = asTestQuestions(docs);
    const totalMarks = questions.reduce((sum, item) => sum + item.marks, 0);
    const seconds = docs.reduce((sum, doc) => sum + Number(doc.estimatedTimeSeconds || 60), 0);
    const test = await Assessment.create({
        title: `${topic.name} MCQ Test`,
        description: `MCQ practice test for ${topic.name}.`,
        type: "topic_test",
        board: chapter.board, class: chapter.class, group: chapter.group || undefined, subject: chapter.subject,
        chapter: chapter._id, topic: topic._id,
        questions, totalMarks, passingMarks: Math.ceil(totalMarks * 0.4),
        durationMinutes: Math.max(1, Math.ceil(seconds / 60)),
        status: "draft",
        createdBy: adminId,
    });
    await Question.updateMany({ _id: { $in: docs.map(doc => doc._id) } }, { $inc: { usageCount: 1 } });
    return test;
}

// Adds MCQs saved after the topic's test was built to its newest test.
async function addNewQuestions(topic) {
    const tests = await Assessment.find({ ...teacherTests, type: "topic_test", topic: topic._id }).select("questions totalMarks durationMinutes").sort({ createdAt: -1 }).lean();
    if (!tests.length) return 0;
    const used = new Set(tests.flatMap(test => test.questions.map(item => String(item.question))));
    const target = tests[0];
    const room = MAX_TEST_QUESTIONS - target.questions.length;
    const docs = (await Question.find({ ...liveMcq, topic: topic._id, _id: { $nin: [...used] } }).select("_id marks estimatedTimeSeconds").sort({ createdAt: 1, _id: 1 }).limit(Math.max(room, 0)).lean());
    if (!docs.length) return 0;
    const added = asTestQuestions(docs, target.questions.length);
    const totalMarks = target.questions.reduce((sum, item) => sum + Number(item.marks || 1), 0) + added.reduce((sum, item) => sum + item.marks, 0);
    const extraMinutes = Math.ceil(docs.reduce((sum, doc) => sum + Number(doc.estimatedTimeSeconds || 60), 0) / 60);
    await Assessment.updateOne({ _id: target._id }, {
        $push: { questions: { $each: added } },
        $set: { totalMarks, passingMarks: Math.ceil(totalMarks * 0.4), durationMinutes: Math.min(1440, Number(target.durationMinutes || 1) + extraMinutes) },
    });
    await Question.updateMany({ _id: { $in: docs.map(doc => doc._id) } }, { $inc: { usageCount: 1 } });
    return docs.length;
}

function parseOpening(value, now) {
    if (value === undefined || value === null || value === "") return null;
    const date = new Date(value);
    if (typeof value !== "string" || !Number.isFinite(date.getTime())) fail("Choose a valid date and time to publish.");
    if (date <= now) fail("Choose a date and time in the future, or publish now.");
    if (date - now > 366 * 24 * 3600 * 1000) fail("Schedule the test within the next year.");
    return date;
}

/**
 * Switches every test of a topic or a whole chapter on, off, or on at a set time.
 * body: { chapter?, topic?, action: "publish" | "unpublish" | "schedule" | "addNew", startsAt? }
 */
async function changePublishing(body, adminId, now = new Date()) {
    const action = String(body.action || "");
    if (!["publish", "unpublish", "schedule", "addNew", "timing"].includes(action)) fail("Choose publish, unpublish, schedule, add new MCQs or timing.");
    const topicId = body.topic ? String(body.topic) : "";
    const chapterId = body.chapter ? String(body.chapter) : "";
    if (!mongoose.isValidObjectId(topicId || chapterId)) fail("Choose a valid chapter or topic.");

    const topic = topicId ? await Topic.findById(topicId).select("name chapterId").lean() : null;
    if (topicId && !topic) fail("Topic not found.", 404);
    const chapter = await Chapter.findById(topic ? topic.chapterId : chapterId).select("name board class group subject testTiming").lean();
    if (!chapter) fail("Chapter not found.", 404);
    const topics = topic ? [topic] : await Topic.find({ chapterId: chapter._id }).select("name chapterId").lean();

    if (action === "addNew") {
        let added = 0;
        for (const item of topics) added += await addNewQuestions(item);
        return { added, created: 0, changed: 0 };
    }

    if (action === "timing") return changeTiming(body, { topic, chapter, topics }, adminId);

    const startsAt = action === "schedule" ? parseOpening(body.startsAt, now) : null;
    if (action === "schedule" && !startsAt) fail("Choose the date and time to publish.");

    const created = action === "unpublish" ? 0 : await ensureTopicTests(chapter, topics, adminId);

    const scope = topic
        ? { ...teacherTests, type: "topic_test", topic: topic._id }
        : { ...teacherTests, chapter: chapter._id, type: { $in: ["topic_test", "chapter_test"] } };
    let update;
    if (action === "unpublish") update = { $set: { status: "draft" }, $unset: { startsAt: 1 } };
    else {
        // Re-opening a test whose closing time has passed clears that closing time.
        await Assessment.updateMany({ ...scope, endsAt: { $lte: startsAt || now } }, { $unset: { endsAt: 1 } });
        update = startsAt ? { $set: { status: "published", startsAt } } : { $set: { status: "published" }, $unset: { startsAt: 1 } };
    }
    // Tests without questions cannot be published.
    const filter = action === "unpublish" ? scope : { ...scope, "questions.0": { $exists: true } };
    const result = await Assessment.updateMany(filter, update);
    if (action !== "unpublish" && !result.matchedCount) fail(topic ? "Add MCQs to this topic before publishing its test." : "Add MCQs to this chapter's topics before publishing.");
    return { created, changed: result.modifiedCount, added: 0 };
}

// A topic with saved MCQs but no test gets one automatically, so publishing (or timing) is one click.
async function ensureTopicTests(chapter, topics, adminId) {
    let created = 0;
    const withTests = new Set((await Assessment.distinct("topic", { ...teacherTests, type: "topic_test", topic: { $in: topics.map(item => item._id) } })).map(String));
    for (const item of topics) {
        if (withTests.has(String(item._id))) continue;
        if (await createTopicTest(chapter, item, adminId)) created += 1;
    }
    return created;
}

/**
 * Sets how long students get, before or after publishing. Attempts already running keep their time.
 * Topic: every test of the topic. Chapter: the complete chapter test, and with applyToTopics a
 * per-question time also goes to each topic test of the chapter.
 */
async function changeTiming(body, { topic, chapter, topics }, adminId) {
    const timing = parseTiming(body.timing);
    const created = await ensureTopicTests(chapter, topics, adminId);
    const retime = async (filter) => {
        const tests = await Assessment.find(filter).select("_id questions.question").lean();
        if (tests.length) await Assessment.bulkWrite(tests.map(test => ({ updateOne: { filter: { _id: test._id }, update: timingFields(timing, test.questions?.length || 0) } })));
        return tests.length;
    };
    let changed = 0;
    if (topic) {
        changed = await retime({ ...teacherTests, type: "topic_test", topic: topic._id });
        if (!changed) fail("Add MCQs to this topic before setting its time.");
    } else {
        const stored = timing.mode === "per_question" ? { mode: "per_question", secondsPerQuestion: timing.secondsPerQuestion } : { mode: "total", minutes: timing.minutes };
        await Chapter.updateOne({ _id: chapter._id }, { $set: { testTiming: stored } });
        changed += await retime({ ...teacherTests, type: "chapter_test", chapter: chapter._id });
        if (body.applyToTopics && timing.mode === "per_question") changed += await retime({ ...teacherTests, type: "topic_test", chapter: chapter._id });
        changed += 1;
    }
    return { created, changed, added: 0 };
}

module.exports = { publishingOverview, changePublishing, openNow, testState };
