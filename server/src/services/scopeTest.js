const mongoose = require("mongoose");
const Chapter = require("../models/Chapter");
const Topic = require("../models/Topic");
const Assessment = require("../models/Assessment");
const { openNow } = require("./testPublishing");
const mcqFilter = { contentType: { $nin: ["long_question", "short_question"] }, type: { $in: ["standard_mcq", "scenario_mcq"] }, status: { $ne: "archived" } };

async function resolveScope(chapterId, topicId) {
    const id = topicId || chapterId;
    if (!mongoose.isObjectIdOrHexString(id)) throw Object.assign(new Error("Select a valid chapter or topic."), { status: 400 });
    const topic = topicId ? await Topic.findById(topicId).lean() : null;
    if (topicId && !topic) throw Object.assign(new Error("Topic not found."), { status: 404 });
    const chapter = await Chapter.findById(topic ? topic.chapterId : chapterId).lean();
    if (!chapter) throw Object.assign(new Error("Chapter not found."), { status: 404 });
    if (topic && chapterId && String(topic.chapterId) !== chapterId) throw Object.assign(new Error("Topic does not belong to this chapter."), { status: 400 });
    const filter = { chapter: chapter._id, board: chapter.board, class: chapter.class, group: chapter.group, subject: chapter.subject };
    if (topic) filter.topic = topic._id;
    return { chapter, topic, filter };
}

async function createScopeTest(chapterId, topicId) {
    const { chapter, topic, filter } = await resolveScope(chapterId, topicId);
    const generatedKey = { ...filter, type: topic ? "topic_test" : "chapter_test", isAutoGenerated: true };
    const [chapterTopics, topicTests, current] = await Promise.all([
        topic ? [topic] : Topic.find({ chapterId: chapter._id }).select("_id topicNumber").lean(),
        Assessment.find({
        ...filter,
        type: "topic_test",
        // Unpublished and scheduled tests stay out until their opening time.
        ...openNow(),
        isAutoGenerated: { $ne: true },
        createdBy: { $exists: true },
        }).sort({ createdAt: 1, _id: 1 }).lean(),
        Assessment.findOne(generatedKey).lean(),
    ]);

    chapterTopics.sort((left, right) => String(left.topicNumber || "").localeCompare(
        String(right.topicNumber || ""), undefined, { numeric: true, sensitivity: "base" }
    ));
    const testsByTopic = new Map();
    topicTests.forEach((test) => {
        const topicKey = String(test.topic || "");
        if (topicKey) {
            if (!testsByTopic.has(topicKey)) testsByTopic.set(topicKey, []);
            testsByTopic.get(topicKey).push(test);
        }
    });
    const orderedTopicTests = chapterTopics.flatMap((item) => testsByTopic.get(String(item._id)) || []);

    const uniqueQuestions = new Map();
    orderedTopicTests.forEach((test) => {
        [...(test.questions || [])].sort((left, right) => Number(left.order || 0) - Number(right.order || 0)).forEach((item) => {
            const id = String(item.question);
            if (!uniqueQuestions.has(id)) uniqueQuestions.set(id, item);
        });
    });
    const questions = [...uniqueQuestions.values()].map((item, index) => ({
        question: item.question,
        marks: item.marks || 1,
        order: index + 1,
        required: item.required !== false,
    }));
    if (!questions.length) {
        const next = await Assessment.findOne({ ...filter, type: "topic_test", status: "published", startsAt: { $gt: new Date() }, isAutoGenerated: { $ne: true }, createdBy: { $exists: true } }).sort({ startsAt: 1 }).select("startsAt").lean();
        if (next) throw Object.assign(new Error(`This test opens on ${new Date(next.startsAt).toLocaleString("en-GB", { timeZone: "Asia/Karachi", dateStyle: "medium", timeStyle: "short" })} (Pakistan time).`), { status: 403 });
    }
    if (!questions.length) throw Object.assign(new Error(topic ? "No topic test has been published here yet." : "No chapter or topic tests have been published here yet."), { status: 404 });

    const totalMarks = questions.reduce((sum, item) => sum + Number(item.marks || 1), 0);
    const durationMinutes = Math.max(1, orderedTopicTests.reduce((sum, test) => sum + Number(test.durationMinutes || 0), 0));
    const content = {
        title: topic ? `${topic.name} Topic Test` : `${chapter.name} Complete Chapter Test`,
        description: topic ? "All published MCQs for this topic." : "A complete chapter test assembled from all published topic tests.",
        ...generatedKey,
        questions,
        durationMinutes,
        totalMarks,
        passingMarks: Math.ceil(totalMarks * 0.4),
        status: "published",
        createdBy: orderedTopicTests[0].createdBy,
    };
    // Previews and starts read this often; only write when the published content changed.
    if (current && sameGeneratedContent(current, content)) return current;
    const save = upsert => Assessment.findOneAndUpdate(generatedKey, content, { returnDocument: "after", upsert, setDefaultsOnInsert: true }).lean();
    try {
        return await save(true);
    } catch (error) {
        // A concurrent request created it first; update that single generated test.
        if (error.code !== 11000) throw error;
        return save(false);
    }
}

const questionSignature = questions => JSON.stringify((questions || []).map(item => [String(item.question), Number(item.marks || 1), Number(item.order || 0), item.required !== false]));

function sameGeneratedContent(current, content) {
    return ["title", "description", "durationMinutes", "totalMarks", "passingMarks", "status"].every(key => current[key] === content[key])
        && String(current.createdBy) === String(content.createdBy)
        && questionSignature(current.questions) === questionSignature(content.questions);
}

module.exports = { resolveScope, createScopeTest, mcqFilter };
