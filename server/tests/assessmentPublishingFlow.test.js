const { test, afterEach, mock } = require("node:test");
const assert = require("node:assert/strict");
const mongoose = require("mongoose");
const Assessment = require("../src/models/Assessment");
const Question = require("../src/models/Question");
const { getQuestions, deleteQuestion } = require("../src/controllers/questionBankController");
const { updateAssessment } = require("../src/controllers/assessmentController");
const id = () => new mongoose.Types.ObjectId();
const query = (result) => ({
    select() { return this; }, populate() { return this; }, sort() { return this; },
    skip() { return this; }, limit() { return this; }, lean: async () => result,
});
const response = () => ({ json(body) { this.body = body; }, status() { return this; } });
afterEach(() => mock.restoreAll());

test("published MCQ directory filters by topic and published source tests, including pagination counts", async () => {
    const topic = id(); const question = id(); let sourceFilter; let questionFilter; let countFilter;
    mock.method(Assessment, "distinct", async (field, filter) => {
        assert.equal(field, "questions.question"); sourceFilter = filter; return [question];
    });
    mock.method(Question, "find", (filter) => { questionFilter = filter; return query([{ _id: question }]); });
    mock.method(Question, "countDocuments", async (filter) => { countFilter = filter; return 1; });
    const res = response();
    await getQuestions({ query: { topic: String(topic), publishedOnly: "true", page: "1", limit: "15" } }, res);
    assert.equal(sourceFilter.status, "published");
    assert.equal(sourceFilter.topic, String(topic));
    assert.deepEqual(sourceFilter.isAutoGenerated, { $ne: true });
    assert.deepEqual(questionFilter._id, { $in: [question] });
    assert.deepEqual(questionFilter, countFilter);
    assert.equal(res.body.pagination.total, 1);
});

test("deleting a published MCQ removes it from every batch and computed test without deleting history", async () => {
    const removed = id(); const retained = id();
    mock.method(Question, "findOne", () => query({ _id: removed }));
    mock.method(Assessment, "find", () => query([
        { _id: id(), questions: [{ question: removed, marks: 1 }], passingMarks: 1 },
        { _id: id(), questions: [{ question: removed, marks: 1 }, { question: retained, marks: 2 }], passingMarks: 3 },
    ]));
    let updates;
    mock.method(Assessment, "bulkWrite", async (operations) => { updates = operations; });
    mock.method(Question, "updateMany", async (_filter, update) => {
        assert.equal(update.status, "archived"); return { modifiedCount: 1 };
    });
    const res = response();
    await deleteQuestion({ params: { id: String(removed) } }, res);
    assert.equal(res.body.removedFromTests, 2);
    assert.equal(updates[0].updateOne.update.$set.status, "archived");
    assert.deepEqual(updates[1].updateOne.update.$set.questions, [{ question: retained, marks: 2 }]);
    assert.equal(updates[1].updateOne.update.$set.totalMarks, 2);
    assert.equal(updates[1].updateOne.update.$set.passingMarks, 2);
});

test("republishing keeps the selected questions and custom duration while recalculating totals", async () => {
    const question = id(); const scope = { board: id(), class: id(), subject: id(), chapter: id(), topic: id() };
    const existing = { _id: id(), ...scope, type: "topic_test", title: "Topic test", status: "published", durationMinutes: 17, questions: [{ question, marks: 2, order: 1 }] };
    mock.method(Assessment, "findById", () => query(existing));
    mock.method(Question, "find", () => query([{ _id: question, marks: 2, estimatedTimeSeconds: 60 }]));
    let update;
    mock.method(Assessment, "findByIdAndUpdate", async (_id, payload) => { update = payload; return { ...existing, ...payload }; });
    const res = response();
    await updateAssessment({ params: { id: String(existing._id) }, body: { status: "published" } }, res);
    assert.equal(update.status, "published");
    assert.equal(update.durationMinutes, 17);
    assert.equal(update.totalMarks, 2);
    assert.equal(String(update.questions[0].question), String(question));
});
