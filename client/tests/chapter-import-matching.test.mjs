import assert from "node:assert/strict";
import { matchTopic, detectKind, normalizeNumber } from "../src/admin/components/chapterImportMatching.js";
const topics = [["2.1","Distance and Displacement"],["2.2","Speed and Velocity"],["2.10","Equations of Motion"],["2.3.1","Acceleration"]].map(([topicNumber,name],i)=>({_id:String(i),topicNumber,name}));
const m = n => matchTopic(n, topics, 2)?.topicNumber ?? null;
assert.equal(m("2.1 MCQs.xlsx"), "2.1");
assert.equal(m("2.10.xlsx"), "2.10");
assert.equal(m("Topic 2-2 short.xlsx"), "2.2");
assert.equal(m("02.03.01 long.xlsx"), "2.3.1");
assert.equal(m("Ch 2 topic 2.2 mcqs.xlsx"), "2.2");
assert.equal(m("2 mcq.xlsx"), "2.2");
assert.equal(m("speed and velocity.xlsx"), "2.2");
assert.equal(m("random.xlsx"), null);
assert.equal(detectKind("2.1 short.xlsx","standard_mcq"), "short_question");
assert.equal(detectKind("2.1 Long Questions.xlsx","standard_mcq"), "long_question");
assert.equal(detectKind("2.1 scenario mcqs.xlsx","standard_mcq"), "scenario_mcq");
assert.equal(detectKind("2.1.xlsx","long_question"), "long_question");
assert.equal(detectKind("2.1_SQ.xlsx","standard_mcq"), "short_question");
assert.equal(normalizeNumber(" Topic 02.10. "), "2.10");
console.log("chapter import matching ok");
